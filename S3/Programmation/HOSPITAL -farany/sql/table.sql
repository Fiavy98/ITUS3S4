NOCACHE;

CREATE OR REPLACE FUNCTION seq_client_nextVal
RETURN NUMBER
AS
    v_next NUMBER;
BEGIN
    SELECT seq_client.NEXTVAL INTO v_next FROM dual;
    RETURN v_next;
END;
