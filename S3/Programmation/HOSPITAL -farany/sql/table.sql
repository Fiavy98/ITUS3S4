CREATE TABLE Usr (
    ID NUMBER PRIMARY KEY,
    name VARCHAR2(100),
    prenom VARCHAR2(100),
    mdp VARCHAR2(50),
    id_poste VARCHAR2(100)
);


--CREE UNE SEQUENCE == (auto-increment)

-- SEQ USER
CREATE SEQUENCE seq_usr
START WITH 1
INCREMENT BY 1;

--TIGGER USER
CREATE OR REPLACE TRIGGER trg_usr_id
BEFORE INSERT ON Usr
FOR EACH ROW
BEGIN
    IF :NEW.ID IS NULL THEN
        :NEW.ID := seq_usr.NEXTVAL;
    END IF;
END;
/


